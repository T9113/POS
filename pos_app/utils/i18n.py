CURRENT_LANG = "en"

def set_language(lang_code: str):
    global CURRENT_LANG
    if lang_code in STRINGS:
        CURRENT_LANG = lang_code

def get_language() -> str:
    return CURRENT_LANG

def t(key: str) -> str:
    """Translate key using active language, fallback to English then key itself."""
    return STRINGS.get(CURRENT_LANG, {}).get(key) or STRINGS["en"].get(key, key)
